proect = input('Введите название проекта: ')
n = int(input('Введите количество участников: '))
resurs = int(input('Введите стоимость одного условного ресурса на одного участника: '))
mes = int(input('Введите количество месяцев работы: '))
name = input('Введите имя ответственного студента: ')

print('=' * 30)
print('Проект : ', proect)
print('Ответственный студент: ', name)
print('Количество участников : ', n)
print('Расход на всех участников за один месяц : ', n * resurs)
print('Общий расход :', n * resurs * mes)
print('Длина названия проекта: ', len(proect))
print('Первый и последний символ названия проекта', proect[0], 'и', proect[-1])
