b = int(input('Введите стоимость одного билета: '))
n = int(input('Введите количество человек: '))
y = int(input('Введите стоимость дополнительной услуги на одного человека: '))


print('стоимость всех билетов = ', b * n)
print('стоимость дополнительных услуг = ', y * n)
print('общая сумма = ', (b + y) * n)